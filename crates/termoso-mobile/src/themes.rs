//! Terminal colour schemes: the Termoso pair plus the community set, in
//! xterm's 16-colour order. Mirrors the desktop registry so a vault synced
//! between devices renders the same. Settings store a scheme by `id`; names
//! are accepted too for profiles written before ids existed.

use crate::terminal::TerminalPalette;

#[derive(Debug, Clone, uniffi::Record)]
pub struct TerminalTheme {
    pub id: String,
    pub name: String,
    /// Dark background — groups the gallery.
    pub dark: bool,
    pub palette: TerminalPalette,
}

pub const TERMOSO_DARK: &str = "termoso-dark";
pub const TERMOSO_LIGHT: &str = "termoso-light";

fn luminance(rgb: u32) -> f32 {
    let r = ((rgb >> 16) & 255) as f32;
    let g = ((rgb >> 8) & 255) as f32;
    let b = (rgb & 255) as f32;
    (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255.0
}

fn t(
    id: &str,
    name: &str,
    background: u32,
    foreground: u32,
    cursor: u32,
    ansi: [u32; 16],
) -> TerminalTheme {
    TerminalTheme {
        id: id.to_string(),
        name: name.to_string(),
        dark: luminance(background) < 0.5,
        palette: TerminalPalette {
            foreground,
            background,
            cursor,
            ansi: ansi.to_vec(),
        },
    }
}

/// Every bundled scheme, Termoso pair first.
#[uniffi::export]
pub fn terminal_themes() -> Vec<TerminalTheme> {
    all()
}

/// Look a scheme up by id or display name.
#[uniffi::export]
pub fn terminal_theme(key: String) -> Option<TerminalTheme> {
    let key = key.trim();
    all().into_iter().find(|t| t.id == key || t.name == key)
}

pub(crate) fn palette_for(key: &str) -> TerminalPalette {
    terminal_theme(key.to_string())
        .map(|t| t.palette)
        .unwrap_or_else(TerminalPalette::termoso_dark)
}

